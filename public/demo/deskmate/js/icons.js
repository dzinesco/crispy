export function sprite(rows, { label = '' } = {}) {
  const height = rows.length;
  const width = rows.reduce((max, row) => Math.max(max, row.length), 0);
  let body = '';
  for (let y = 0; y < height; y += 1) {
    const row = rows[y];
    for (let x = 0; x < row.length; x += 1) {
      const fill = INK[row[x]];
      if (!fill) continue;
      body += `<rect x="${x}" y="${y}" width="1" height="1" fill="${fill}"/>`;
    }
  }
  const named = label
    ? ` role="img" aria-label="${label}"`
    : ' aria-hidden="true"';
  return `<svg viewBox="0 0 ${width} ${height}" shape-rendering="crispEdges"${named}>${body}</svg>`;
}

